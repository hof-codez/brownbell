// test-roster-drop-fix.js
// Offline sanity check for resolveDroppedOrInjuredSubs - no network calls.
// Simulates: TestTeam's active substitute was dropped from their roster weeks ago.
// Before the fix: this sub would sit "active" forever, or (on the Tuesday/Thursday
// path) get correctly detected but then silently not replaced due to the stub.
// After the fix: the old sub gets endWeek set, and a valid replacement is recorded.

process.env.SUPABASE_URL = process.env.SUPABASE_URL || 'http://fake';
process.env.SUPABASE_SERVICE_ROLE_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY || 'fake';

const BrownBellAutomator = require('./update-standings.js');

async function run() {
    const automator = new BrownBellAutomator('test-league');

    // Fake players: original duo player, a dropped substitute, and a fresh valid candidate
    automator.playersData = {
        '1001': { first_name: 'Original', last_name: 'Player', position: 'QB', injury_status: null, years_exp: 5 },
        '2002': { first_name: 'Dropped', last_name: 'Sub', position: 'RB', injury_status: null, years_exp: 3 },
        '3003': { first_name: 'Fresh', last_name: 'Candidate', position: 'RB', injury_status: null, years_exp: 2 }
    };

    // Live roster for TestTeam only contains the fresh candidate - the dropped sub (2002)
    // and even the original injured player (1001) are gone, simulating real churn.
    automator.leagueData = {
        rosters: [
            { owner_id: 'owner1', roster_id: 1, players: ['3003'] }
        ],
        userMap: { owner1: 'TestTeam' }
    };

    automator.knownDuos.main = {
        TestTeam: [
            { name: 'Original Player', position: 'QB' },
            { name: 'Other Player', position: 'WR' }
        ]
    };
    automator.knownDuos.nextup = {};

    // Stub out network-dependent helpers so this runs fully offline
    automator.getWeeklyScores = async () => ({});
    automator.hasPlayerGameStarted = async () => false;
    automator.isPlayerOnBye = () => false;

    const existingSubstitutions = [{
        teamName: 'TestTeam',
        playerIndex: 0,
        awardType: 'main',
        originalName: 'Original Player',
        originalPosition: 'QB',
        substituteName: 'Dropped Sub',
        substitutePlayerId: '2002',
        substitutePosition: 'RB',
        startWeek: 3,
        endWeek: null,
        active: true,
        autoGenerated: true,
        reason: 'Injury Checkpoint (3) - out'
    }];

    const week = 6;
    const { injuredSubs, forcedSubstitutions } = await automator.resolveDroppedOrInjuredSubs(week, existingSubstitutions);

    console.log('injuredSubs detected:', injuredSubs.length);
    console.log('forcedSubstitutions produced:', JSON.stringify(forcedSubstitutions, null, 2));
    console.log('old sub endWeek after resolution:', existingSubstitutions[0].endWeek);

    // Assertions
    const oldSubEnded = existingSubstitutions[0].endWeek === week - 1;
    const replacementFound = forcedSubstitutions.some(s =>
        s.teamName === 'TestTeam' && s.substitutePlayerId === '3003' && !s.noReplacementAvailable
    );

    console.log('\n--- RESULTS ---');
    console.log(oldSubEnded ? '✅ Old dropped sub correctly ended' : '❌ Old dropped sub was NOT ended');
    console.log(replacementFound ? '✅ Valid replacement correctly recorded' : '❌ Replacement was NOT recorded');

    if (!oldSubEnded || !replacementFound) {
        process.exit(1);
    }
    console.log('\n✅ ALL CHECKS PASSED');
}

run().catch(err => {
    console.error('Test threw an error:', err);
    process.exit(1);
});
